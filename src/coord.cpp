namespace {
static int Min_Int(int a, int b) { return (a < b) ? a : b; }

static int32_t Floor_Div_256(int32_t value) {
    if (value >= 0) return value >> 8;
    return -(((-value) + 255) >> 8);
}

static int Calc_Delta(signed short factor, short distance) {
    int32_t product = static_cast<int32_t>(factor) * static_cast<int32_t>(distance);
    product *= 2;
    int32_t shifted = Floor_Div_256(product);
    int16_t word = static_cast<int16_t>(shifted);
    return static_cast<int>(word);
}

static DirType Random_Pick(DirType low, DirType high) {
    if (high < low) {
        DirType tmp = low;
        low = high;
        high = tmp;
    }
    int span = static_cast<int>(high - low) + 1;
    if (span <= 0) return low;
    return static_cast<DirType>(low + (std::rand() % span));
}
}  // namespace

short const* Coord_Spillage_List(COORDINATE coord, int maxsize) {
    static short const MoveSpillage[(int)FACING_COUNT + 1][5] = {
        {0, -MAP_CELL_W, REFRESH_EOL, 0, 0},                     // N
        {0, -MAP_CELL_W, 1, -(MAP_CELL_W - 1), REFRESH_EOL},     // NE
        {0, 1, REFRESH_EOL, 0, 0},                               // E
        {0, 1, MAP_CELL_W, MAP_CELL_W + 1, REFRESH_EOL},         // SE
        {0, MAP_CELL_W, REFRESH_EOL, 0, 0},                      // S
        {0, -1, MAP_CELL_W, MAP_CELL_W - 1, REFRESH_EOL},        // SW
        {0, -1, REFRESH_EOL, 0, 0},                              // W
        {0, -1, -MAP_CELL_W, -(MAP_CELL_W + 1), REFRESH_EOL},    // NW
        {0, REFRESH_EOL, 0, 0, 0}                                // non-moving
    };

    static short manual[10];
    static char const SpillTable[16] = {8, 6, 2, -1, 0, 7, 1, -1, 4, 5, 3, -1, -1, -1, -1, -1};

    int index = 0;
    int x, y;

    if (maxsize > ICON_PIXEL_W * 2) {
        static short const gigundo[] = {
            -((2 * MAP_CELL_W) - 2), -((2 * MAP_CELL_W) - 1), -((2 * MAP_CELL_W)),     -((2 * MAP_CELL_W) + 1),
            -((2 * MAP_CELL_W) + 2), -((1 * MAP_CELL_W) - 2), -((1 * MAP_CELL_W) - 1), -((1 * MAP_CELL_W)),
            -((1 * MAP_CELL_W) + 1), -((1 * MAP_CELL_W) + 2), -((0 * MAP_CELL_W) - 2), -((0 * MAP_CELL_W) - 1),
            -((0 * MAP_CELL_W)),     -((0 * MAP_CELL_W) + 1), -((0 * MAP_CELL_W) + 2), ((1 * MAP_CELL_W) - 2),
            ((1 * MAP_CELL_W) - 1),  ((1 * MAP_CELL_W)),      ((1 * MAP_CELL_W) + 1),  ((1 * MAP_CELL_W) + 2),
            +((2 * MAP_CELL_W) - 2), +((2 * MAP_CELL_W) - 1), +((2 * MAP_CELL_W)),     +((2 * MAP_CELL_W) + 1),
            +((2 * MAP_CELL_W) + 2), REFRESH_EOL};
        return &gigundo[0];
    }

    if (maxsize > ICON_PIXEL_W) {
        maxsize = Min_Int(maxsize, (ICON_PIXEL_W * 2)) / 2;

        x = Fixed_To_Cardinal(ICON_PIXEL_W, Coord_XLepton(coord));
        y = Fixed_To_Cardinal(ICON_PIXEL_H, Coord_YLepton(coord));
        int left = x - maxsize;
        int right = x + maxsize;
        int top = y - maxsize;
        int bottom = y + maxsize;

        manual[index++] = 0;
        if (left < 0) manual[index++] = -1;
        if (right >= ICON_PIXEL_W) manual[index++] = 1;
        if (top < 0) manual[index++] = -MAP_CELL_W;
        if (bottom >= ICON_PIXEL_H) manual[index++] = MAP_CELL_W;
        if (left < 0 && top < 0) manual[index++] = -(MAP_CELL_W + 1);
        if (right >= ICON_PIXEL_W && bottom >= ICON_PIXEL_H) manual[index++] = MAP_CELL_W + 1;
        if (left < 0 && bottom >= ICON_PIXEL_H) manual[index++] = MAP_CELL_W - 1;
        if (right >= ICON_PIXEL_H && top < 0) manual[index++] = -(MAP_CELL_W - 1);
        manual[index] = REFRESH_EOL;
        return &manual[0];
    }

    int posval = Pixel2Lepton[(ICON_PIXEL_W - maxsize) / 2];

    x = Coord_XLepton(coord) - 0x0080;
    y = Coord_YLepton(coord) - 0x0080;
    if (y > posval) index |= 0x08;
    if (y < -posval) index |= 0x04;
    if (x > posval) index |= 0x02;
    if (x < -posval) index |= 0x01;

    int spill = SpillTable[index];
    if (spill < 0) spill = static_cast<int>(FACING_COUNT);
    return &MoveSpillage[spill][0];
}

COORDINATE Coord_Move(COORDINATE start, DirType dir, unsigned short distance) {
    short x = static_cast<short>(Coord_X(start));
    short y = static_cast<short>(Coord_Y(start));

    Move_Point(x, y, dir, distance);
    return XYP_COORD(x, y);
}

COORDINATE Coord_Scatter(COORDINATE coord, unsigned distance, bool lock) {
    static const DirType DIR_MAX = 255;

    COORDINATE newcoord = Coord_Move(coord, Random_Pick(DIR_N, DIR_MAX), static_cast<unsigned short>(distance));

    if (newcoord & 0xC000C000L) newcoord = coord;

    if (lock) {
        newcoord = Coord_Snap(newcoord);
    }

    return newcoord;
}

